#!/bin/bash
# Deploys Ghost's analytics schema to tinybird-local, then writes the
# workspace ID and tokens to /out/tokens.env (= ./tinybird/tokens.env on the host).
# Adapted from Ghost's docker/tb-cli/entrypoint.sh.
set -euo pipefail
rm -f /tmp/ready

TB_URL="${TB_HOST:-http://tinybird-local:7181}"

echo "Deploying Ghost's Tinybird schema to tinybird-local..."
tb --local deploy --wait

TB_INFO=$(tb --output json info)
WORKSPACE_ID=$(echo "$TB_INFO" | jq -r '.local.workspace_id')
WORKSPACE_TOKEN=$(echo "$TB_INFO" | jq -r '.local.token')

if [ -z "$WORKSPACE_ID" ] || [ "$WORKSPACE_ID" = "null" ] || [ -z "$WORKSPACE_TOKEN" ] || [ "$WORKSPACE_TOKEN" = "null" ]; then
  echo "Error: couldn't read workspace ID/token from tinybird-local" >&2
  exit 1
fi

ADMIN_TOKEN=""
TRACKER_TOKEN=""
for i in $(seq 1 10); do
  if TOKENS=$(curl -fsS -H "Authorization: Bearer $WORKSPACE_TOKEN" "$TB_URL/v0/tokens"); then
    ADMIN_TOKEN=$(echo "$TOKENS" | jq -r '[.tokens[] | select(.scopes[]? | .type == "ADMIN") | .token][0] // empty')
    TRACKER_TOKEN=$(echo "$TOKENS" | jq -r '[.tokens[] | select(.name == "tracker") | .token][0] // empty')
    [ -n "$ADMIN_TOKEN" ] && [ -n "$TRACKER_TOKEN" ] && break
  fi
  echo "Tokens not ready (attempt $i), retrying..." >&2
  sleep 2
done

if [ -z "$ADMIN_TOKEN" ] || [ -z "$TRACKER_TOKEN" ]; then
  echo "Error: couldn't get admin/tracker tokens from tinybird-local" >&2
  exit 1
fi

# Readable by root only (compose reads it as root): it holds the admin token
umask 077
cat > /out/tokens.env.tmp <<EOF
# Generated by tb-setup - do not edit, do not share
tinybird__workspaceId=$WORKSPACE_ID
tinybird__adminToken=$ADMIN_TOKEN
TINYBIRD_TRACKER_TOKEN=$TRACKER_TOKEN
EOF
mv /out/tokens.env.tmp /out/tokens.env
echo "Wrote /out/tokens.env"

# Done. TB_SETUP_EXIT=1 (the kit's Kubernetes Job, k8s/components/analytics/) ends here; else mark healthy and idle
# so the container (and its stack) stays "running".
[ "${TB_SETUP_EXIT:-}" = 1 ] && exit 0
touch /tmp/ready
trap 'exit 0' TERM INT
while :; do sleep 3600 & wait $!; done
