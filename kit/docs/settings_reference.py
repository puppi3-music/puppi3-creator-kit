#!/usr/bin/env python3
"""Writes the kit's Settings reference (kit/docs/settings-reference.html) from the files a site's settings come from,
so it can't go stale: instances/example.env (site.env), each stack's .env.example and the kit's own examples
(secrets/<stack>.env), k8s's (secrets and cloud-<overlay>.env), the bridge's fixed settings in its compose file, and
which settings setup.sh asks for or makes. Only the part between the page's "generated" markers is written; the rest
of the page is by hand.

It also checks the settings themselves, and stops (exit 1) when:
- a compose file, profile or Traefik template reads a variable no example documents (and isn't in SET_FOR_YOU)
- an example documents a variable nothing reads any more
- an optional key's default in an example (#KEY=value) isn't the compose files' own (${KEY:-value})
- the reference would carry puppi3.party's own names (PRIVATE_WORDS)

    python3 kit/docs/settings_reference.py           # write the page
    python3 kit/docs/settings_reference.py --check   # exit 1 if the page is stale or a check fails
docs/build-docs.py runs it too (and its --check), before copying the shared styles in.
"""
import html
import os
import re
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PAGE = os.path.join(REPO, "kit", "docs", "settings-reference.html")
BLOCK = re.compile(r"(<!-- generated by kit/docs/settings_reference\.py: -->\n).*?(<!-- /generated -->)", re.S)
TOC = re.compile(r"(<!-- generated contents -->\n).*?(<!-- /generated contents -->)", re.S)

# (h3 id, file in the site's folder, example files it's made from, what it's for, check that something reads each key)
SECRETS = [
    ("secrets-traefik", "secrets/traefik.env", ["stacks/traefik/.env.example"],
     "Traefik's certificates.", True),
    ("secrets-puppi3", "secrets/puppi3.env", ["stacks/puppi3/.env.example"],
     "Ghost's database login (the Ghost stack is called puppi3 for now).", True),
    ("secrets-postiz", "secrets/postiz.env", ["stacks/postiz/.env.example"],
     "The social module: Postiz, each network's developer app, and the bridge's keys and options.", True),
    ("secrets-icecast", "secrets/icecast.env", ["stacks/icecast/.env.example", "kit/examples/icecast.env.example"],
     "The live module: TinyIce's passwords.", True),
    ("secrets-monitoring", "secrets/monitoring.env", ["kit/examples/monitoring.env.example"],
     "The monitoring module: Grafana's logins and where the alerts go.", True),
]
K8S = [
    ("k8s-ghost-mail", "secrets/ghost-mail.env", ["k8s/examples/ghost-mail.env.example"],
     "Ghost's mail on Kubernetes (on Compose it's in Ghost's config file, data/puppi3/ghost/config.production.json).", False),
    ("k8s-cloud", "secrets/cloud.env", ["k8s/examples/cloud.env.example"],
     "The cloud database's master login (eks and gke, with the social module).", True),
    ("k8s-s3", "secrets/s3.env", ["k8s/examples/s3.env.example"],
     "The bucket's keys, where the cloud has no role for Ghost to take (gke's HMAC key).", True),
    ("k8s-eks", "cloud-eks.env", ["k8s/overlays/eks/cloud.env.example"],
     "What the eks overlay needs from AWS: k8s/up.sh &lt;folder&gt; eks reads it.", True),
    ("k8s-gke", "cloud-gke.env", ["k8s/overlays/gke/cloud.env.example"],
     "What the gke overlay needs from Google Cloud: k8s/up.sh &lt;folder&gt; gke reads it.", True),
]

# Read by the compose files or Traefik's templates, but set by the kit itself (or only by a second site behind
# another Traefik): never in a site's files. Each must still be read somewhere, or the check says so.
SET_FOR_YOU = {
    "SITE_DIR": "kit.sh: the site's folder.",
    "LIVE_MOUNT": "kit.sh and k8s/up.sh: the mount your streaming software sends to, read from TinyIce's own config, so "
                  "the bridge counts the right one.",
    "GHOST_UPSTREAM": "The kit's Traefik profile (and k8s's Traefik): where Ghost answers.",
    "ANALYTICS_UPSTREAM": "Where Ghost's analytics service answers (the kit's own name is the default).",
    "TINYBIRD_UPSTREAM": "Where Tinybird answers (the kit's own name is the default).",
    "BRIDGE_UPSTREAM": "Where the bridge answers (the kit's own name is the default).",
    "SITE_MIDDLEWARES": "Extra Traefik middlewares on the site's router, for a second site behind the same Traefik "
                        "(a staging copy's red bar).",
    "ADMIN_MIDDLEWARES": "The same, on Ghost Admin's router.",
    "UPSTREAM_PROXY": "A proxy in front of Traefik whose X-Real-Ip header is believed (a staging copy behind the "
                      "main Traefik).",
    "ENTRYPOINT": "Traefik's entry point for the site's routers (websecure unless a second site needs another).",
}

# What the reference must never say: the names of the site the kit was built for, and its NAS (the kit's guides are
# for anyone)
PRIVATE_WORDS = re.compile(r"puppi3\.party|nas\.pet|butterwoof|Dockge|NVMe2|Toronto|Traktor", re.I)

# The files that read settings, for the checks: a ${VAR} or Traefik's env "VAR" there must be documented
READERS = ["stacks/traefik/compose.yaml", "stacks/puppi3/compose.yaml", "stacks/postiz/compose.yaml",
           "stacks/icecast/compose.yaml", "kit/compose.yaml", "kit/monitoring/compose.yaml"]
# ...and where a documented key may be read (a whole-word match outside the example files)
USERS = ["stacks/traefik", "stacks/puppi3", "stacks/postiz", "stacks/icecast", "stacks/monitoring/grafana", "kit",
         "k8s", "scripts"]

KEY = re.compile(r"^(#)?([A-Za-z_][A-Za-z0-9_]*)=(.*)$")


def esc(s):
    return html.escape(s, quote=False)


def read(rel):
    with open(os.path.join(REPO, rel), encoding="utf-8") as f:
        return f.read()


def parse(rel):
    """An example file as groups: the comment lines above some keys, and those keys (name, value, commented out).
    A blank line ends a group; so does a comment after keys. Blocks that only repeat site.env's values, and the
    stack files' header line, are left out by the caller."""
    groups, note, keys = [], [], []
    for line in read(rel).splitlines():
        s = line.strip()
        m = KEY.match(s)   # KEY=value, or #KEY=value (optional: the default shown)
        if not s:
            if keys: groups.append((note, keys))
            note, keys = [], []
        elif m:
            keys.append((m.group(2), m.group(3), bool(m.group(1))))
        elif s.startswith("#"):
            if keys:
                groups.append((note, keys)); note, keys = [], []
            note.append(s.lstrip("#").strip())
    if keys: groups.append((note, keys))
    return groups


def setup_roles():
    """What kit/setup.sh does with each key: asks for it (site.env), or fills it in itself (random or derived)."""
    sh = read("kit/setup.sh")
    asked = set(re.findall(r"\bask ([A-Z_]+) \"", sh))
    made = set(re.findall(r"[\"( ]([A-Za-z_][A-Za-z0-9_]*)=\$\(rand", sh))
    derived = set(re.findall(r"setkey \"\$SITE_DIR/site\.env\" ([A-Z_]+) ", sh))
    derived |= set(re.findall(r"\"([A-Za-z_][A-Za-z0-9_]*)=", sh))
    return asked, made, derived - asked - made


def linkify(text, known):
    """Escapes a note and links the setting names it mentions to their rows."""
    out = esc(text)
    return re.sub(r"\b([A-Z][A-Z0-9]*_[A-Z0-9_]+|[a-z]+__[a-z_]+)\b",
                  lambda m: f'<a href="#var-{m.group(1)}"><code>{m.group(1)}</code></a>' if m.group(1) in known
                  else f"<code>{m.group(1)}</code>", out)


def rows(groups, known, roles, skip=()):
    asked, made, derived = roles
    out = []
    for note, keys in groups:
        keys = [k for k in keys if k[0] not in skip]
        if not keys:
            continue
        names, values = [], []
        for name, value, optional in keys:
            pills = []
            if optional: pills.append(' <span class="pill skip">optional</span>')
            if name in asked: pills.append(' <span class="pill you">setup asks</span>')
            elif name in made: pills.append(' <span class="pill auto">setup makes it</span>')
            elif name in derived: pills.append(' <span class="pill auto">setup fills it in</span>')
            names.append(f'<code id="var-{name}">{name}</code>' + "".join(pills))
            values.append(f"<code>{esc(value)}</code>" if value else '<span class="none">empty</span>')
        # (a space before each <br>, so search's snippets don't run the names together)
        out.append(f"<tr><td>{' <br>'.join(names)}</td><td>{' <br>'.join(values)}</td>"
                   f"<td>{linkify(' '.join(note), known) or ''}</td></tr>")
    return out


def table(trs, head=("Setting", "Example or default", "What it's for")):
    return ('<div class="tablewrap"><table>\n<thead><tr>' + "".join(f"<th>{h}</th>" for h in head) +
            "</tr></thead>\n<tbody>\n" + "\n".join(trs) + "\n</tbody></table></div>")


def bridge_fixed():
    """The bridge's settings with a fixed value in its compose file (no ${...}), with the comment beside each."""
    text = read("stacks/postiz/compose.yaml")
    env = text.split("postiz-ghost-bridge:", 1)[1].split("environment:", 1)[1].split("    volumes:", 1)[0]
    out, last = [], None
    for line in env.splitlines():
        m = re.match(r'^      ([A-Z_]+): "([^"$]*)"\s*(?:#\s*(.*))?$', line)
        cont = re.match(r"^ {20,}#\s*(.*)$", line)
        if m and "://" not in m.group(2) and not m.group(1).startswith("POSTIZ_DB_"):
            last = [m.group(1), m.group(2), m.group(3) or ""]
            out.append(last)
        elif cont and last is not None:
            last[2] += "; " + cont.group(1)
        else:
            last = None
    return out


def compose_vars():
    found = {}
    for rel in READERS + [os.path.join("kit/profiles", f) for f in sorted(os.listdir(os.path.join(REPO, "kit/profiles")))]:
        for line in read(rel).splitlines():
            if line.lstrip().startswith("#"):
                continue
            for v in re.findall(r"\$\{([A-Za-z_][A-Za-z0-9_]*)", line):
                found.setdefault(v, rel)
    tdir = "stacks/traefik/dynamic"
    for f in sorted(os.listdir(os.path.join(REPO, tdir))):
        if f.endswith(".yml"):
            for v in re.findall(r'env "([A-Z_]+)"', read(os.path.join(tdir, f))):
                found.setdefault(v, os.path.join(tdir, f))
    return found


def compose_defaults():
    """Each ${VAR:-default} (or ${VAR-default}) default the readers give, by name (none when they disagree)."""
    found = {}
    for rel in READERS:
        for line in read(rel).splitlines():
            if line.lstrip().startswith("#"):
                continue
            for name, value in re.findall(r"\$\{([A-Za-z_][A-Za-z0-9_]*):?-([^}$]*)\}", line):
                found.setdefault(name, set()).add(value)
    return {n: v.pop() for n, v in found.items() if len(v) == 1}


def read_somewhere(name, examples):
    # (--untracked: new files count, and so does a fresh repo whose files aren't committed yet)
    r = subprocess.run(["git", "grep", "--untracked", "-l", "-w", "-e", name, "--", *USERS], cwd=REPO,
                       capture_output=True, text=True)
    files = [f for f in r.stdout.split() if not f.endswith(".example") and not f.endswith(".md") and f != PAGE_REL]
    return bool(files)


PAGE_REL = "kit/docs/settings-reference.html"


def generate():
    roles = setup_roles()
    site = [(n, [k for k in ks if k[0] != "DATA_DIR"]) for n, ks in parse("instances/example.env")]
    site_keys = {k[0] for _, ks in site for k in ks} | {"DATA_DIR"}
    sources = {}
    for sid, fname, examples, about, check in SECRETS + K8S:
        groups = []
        for ex in examples:
            for note, keys in parse(ex):
                # the stack files' header ("Variables for the ... stack's .env") and their site.env repeats
                note = [n for n in note if not n.startswith("Variables for the ")]
                if keys and all(k[0] in site_keys for k in keys):
                    continue
                groups.append((note, keys))
        sources[sid] = (fname, examples, about, check, groups)
    fixed = bridge_fixed()
    known = site_keys | set(SET_FOR_YOU) | {k[0] for *_, g in sources.values() for _, ks in g for k in ks} \
        | {f[0] for f in fixed}

    problems = []
    used = compose_vars()
    for v, where in sorted(used.items()):
        if v not in known and v != "VAR":
            problems.append(f"{where} reads ${{{v}}}, which no example documents (or add it to SET_FOR_YOU)")
    for v in SET_FOR_YOU:
        if v not in used:
            problems.append(f"SET_FOR_YOU names {v}, which nothing reads any more")
    checked = [(k[0], ex) for _, ks in site for k in ks for ex in ["instances/example.env"]]
    for fname, examples, about, check, groups in sources.values():
        if check:
            checked += [(k[0], examples[0]) for _, ks in groups for k in ks]
    for name, ex in checked:
        if not read_somewhere(name, ex):
            problems.append(f"{ex} documents {name}, which nothing reads any more")
    # an optional key's default (#KEY=value) must be the one the compose files fall back to
    defaults = compose_defaults()
    shown = [(k, "instances/example.env") for _, ks in site for k in ks]
    shown += [(k, examples[0]) for fname, examples, about, check, groups in sources.values() for _, ks in groups for k in ks]
    for (name, value, optional), ex in shown:
        if optional and name in defaults and defaults[name] != value:
            problems.append(f"{ex} shows {name}={value}, but the compose files default to {defaults[name]!r}")

    parts, toc = [], []

    def section(sid, title, toc_title, body, subs=()):
        parts.append(f'<section id="{sid}">\n  <h2>{title}</h2>\n{body}\n</section>')
        toc.append(f'    <li><a href="#{sid}">{toc_title}</a></li>')

    section("site-env", "site.env: the site", "site.env",
            "  <p>One file of site-wide values, read by every part. It holds no secrets. Setup asks for the first few "
            "and explains every other one in the file itself.</p>\n" +
            table(rows(site, known, roles)) +
            '\n  <p><code id="var-DATA_DIR">DATA_DIR</code>: where the site keeps its data. Leave it unset: '
            "<code>kit.sh</code> sets it to the folder's <code>data/</code>.</p>")

    def files_body(group_ids, intro):
        body = [intro]
        for sid in group_ids:
            fname, examples, about, check, groups = sources[sid]
            body.append(f'  <h3 id="{sid}">{fname}</h3>\n  <p>{about} Made from '
                        + ", ".join(f"<code>{e}</code>" for e in examples) + ".</p>\n"
                        + table(rows(groups, known, roles, skip=site_keys)))
        return "\n".join(body)

    section("secrets", "secrets/: one file per stack", "secrets/",
            files_body([s[0] for s in SECRETS],
                       "  <p>Each stack's passwords and keys, in <code>secrets/&lt;stack&gt;.env</code>. Setup writes "
                       "every file with random passwords; the keys for outside services (each network's app, "
                       "Cloudflare, Search Console) are yours to add. Keep these files private: they're the only "
                       "copy.</p>"))
    section("k8s", "Kubernetes only", "Kubernetes only",
            files_body([s[0] for s in K8S],
                       "  <p>On Kubernetes, <code>k8s/up.sh</code> makes a Secret from each file in "
                       "<code>secrets/</code>, named after it, so these sit beside the ones above. The cloud "
                       "overlays also read <code>cloud-&lt;overlay&gt;.env</code> from the site's folder.</p>"))
    trs = [f'<tr><td><code id="var-{n}">{n}</code></td><td><code>{esc(v)}</code></td><td>{linkify(c, known)}</td></tr>'
           for n, v, c in fixed]
    section("bridge-fixed", "The bridge's fixed settings", "The bridge's fixed settings",
            "  <p>Which numbers the bridge collects. These have one value for every site, in the bridge's compose "
            "file (<code>stacks/postiz/compose.yaml</code>). A site picks its networks with "
            '<a href="#var-NETWORKS"><code>NETWORKS</code></a> instead; how posts are shared is in '
            '<a href="#site-env">site.env</a>.</p>\n' + table(trs))
    trs = [f'<tr><td><code id="var-{n}">{n}</code></td><td>{esc(t)}</td></tr>' for n, t in SET_FOR_YOU.items()]
    section("set-for-you", "Set for you", "Set for you",
            "  <p>The compose files read these too, but the kit sets them itself. A site never needs them.</p>\n"
            + table(trs, head=("Setting", "Who sets it")))

    content = "\n\n".join(parts) + "\n"
    leaks = sorted(set(m.group(0) for m in PRIVATE_WORDS.finditer(content)))
    if leaks:
        problems.append("the reference would say " + ", ".join(leaks) + " (edit the example's comment)")
    return content, "\n".join(toc) + "\n", problems


def render():
    """The page as it should be, and the problems found."""
    page = read(PAGE_REL)
    content, toc, problems = generate()
    page = BLOCK.sub(lambda m: m.group(1) + content + m.group(2), page)
    page = TOC.sub(lambda m: m.group(1) + toc + "    " + m.group(2), page)
    return page, problems


def main(check):
    """Writes (or checks) the page; returns a list of messages for what's wrong (empty: all good)."""
    new, problems = render()
    stale = new != read(PAGE_REL)
    if stale and not check:
        with open(PAGE, "w", encoding="utf-8") as f:
            f.write(new)
    msgs = ["settings_reference: " + p for p in problems]
    if stale and not check:
        print("settings_reference: wrote kit/docs/settings-reference.html")
    if stale and check:
        msgs.append("settings_reference: kit/docs/settings-reference.html is out of date (python3 docs/build-docs.py)")
    return msgs


if __name__ == "__main__":
    msgs = main("--check" in sys.argv[1:])
    print("\n".join(msgs) or "settings_reference: up to date")
    sys.exit(1 if msgs else 0)
